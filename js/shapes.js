export const SHAPE_IDS = Object.keys(SHAPES);

// The shape centred on a size×size board, as a flat 0/1 array (row-major).
export function shapeMask(id, size) {
  const { rows } = SHAPES[id];
  const top = Math.floor((size - rows.length) / 2);
  const left = Math.floor((size - rows[0].length) / 2);
  const mask = new Array(size * size).fill(0);
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') mask[(y + top) * size + x + left] = 1;
    }
  });
  return mask;
}

export const shapeSize = (id) => Math.max(SHAPES[id].rows.length, SHAPES[id].rows[0].length);
